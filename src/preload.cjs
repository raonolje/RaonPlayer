const {contextBridge,ipcRenderer,webUtils}=require('electron');
contextBridge.exposeInMainWorld('native',{
 configureOutput:(pool,display,full,visible)=>ipcRenderer.invoke('configure-output',pool,display,full,visible),
 onOutputClosed:callback=>ipcRenderer.on('output-closed',(_,id)=>callback(id)),
 snapshotAck:()=>ipcRenderer.send('snapshot-ack'),
 previewAck:()=>ipcRenderer.send('preview-ack'),
 onPreviewCredit:callback=>ipcRenderer.on('preview-credit',()=>callback()),
 enginePreview:data=>ipcRenderer.send('engine-preview',data),
 onEnginePreview:callback=>ipcRenderer.on('engine-preview',(_,data)=>callback(data)),
 engineCommand:(method,payload)=>ipcRenderer.invoke('engine-command',method,payload),
 onEngineEvent:callback=>ipcRenderer.on('engine-event',(_,data)=>callback(data)),
 onEngineCommand:callback=>ipcRenderer.on('engine-command',(_,data)=>callback(data)),
 engineReply:data=>ipcRenderer.send('engine-reply',data),
 engineEvent:data=>ipcRenderer.send('engine-event',data),
 engineReady:()=>ipcRenderer.send('engine-ready'),
 environment:()=>ipcRenderer.invoke('environment'),
 outputFullscreen:(id,full)=>ipcRenderer.invoke('output-fullscreen',id,full),
 importMedia:()=>ipcRenderer.invoke('import'),
 importPaths:paths=>ipcRenderer.invoke('import-paths',paths),
 droppedFiles:files=>files.map(f=>webUtils.getPathForFile(f)).filter(Boolean),
 save:(project,as)=>ipcRenderer.invoke('save',project,as),
 open:()=>ipcRenderer.invoke('open'),
 demo:()=>ipcRenderer.invoke('demo'),
 packageProject:p=>ipcRenderer.invoke('package-project',p),
 relink:id=>ipcRenderer.invoke('relink',id),
 pingpong:(id,cue)=>ipcRenderer.invoke('pingpong',id,cue),
 loopFrames:(id,cue,fps)=>ipcRenderer.invoke('loop-frames',id,cue,fps),
 transcode:id=>ipcRenderer.invoke('transcode',id),
 cancelJob:()=>ipcRenderer.invoke('cancel-job'),
 autosave:p=>ipcRenderer.invoke('autosave',p),
 recovery:()=>ipcRenderer.invoke('recovery'),
 onJob:callback=>{ipcRenderer.on('job-progress',(_,data)=>callback(data));}
});
